namespace Enum
{
    /// <summary>
    /// รถประจำทาง 4 คันของกฎข้อ 6 — ทุกคันคือบทจบ ไม่มีคันไหนเป็น "เล่นใหม่"
    ///
    /// ดีไซน์เดิมมีคันที่ 5 (รถหลอก — ขึ้นแล้วกลับมาเลือกใหม่) แต่ถอดออกแล้ว
    /// หน้าที่ของมันถูกแทนด้วยการที่รถวนกลับไปคันที่ 1 เองเมื่อปล่อยผ่านครบ 4 คัน
    /// ผู้เล่นจึงยังได้ "ดูใหม่" ได้ไม่จำกัดโดยไม่ต้องมีรถที่ไม่มีผลอะไร
    ///
    /// ห้ามแทรกตรงกลางหรือสลับลำดับ — ค่านี้ถูก serialize เป็นตัวเลขดิบใน Inspector
    /// ของ Rule6Bus เหมือน RewardKind กับ PhoneState ของใหม่ให้ต่อท้ายอย่างเดียว
    /// </summary>
    public enum Rule6BusKind
    {
        /// <summary>
        /// คันที่ 1 — กับดัก
        ///
        /// ไฟในรถสว่างอุ่น ป้ายหน้ารถเป็นชื่อหมู่บ้านของผู้เล่น คนนั่งเต็มเหลือที่เดียว
        /// ริมหน้าต่างมีเงาผู้ชายก้มดูโทรศัพท์ (คือคนที่ส่งข้อความมาตลอดคืน)
        ///
        /// เหลือที่เดียว = มีที่ให้เราแต่ไม่มีที่ให้แป้ง ขึ้นคันนี้แป้งถูกทิ้งซ้ำรอบที่แล้ว
        /// และเราจะกลายเป็นคนส่งข้อความให้คนต่อไป
        /// </summary>
        Trap = 0,

        /// <summary>
        /// คันที่ 2 — ทางรอด
        ///
        /// ไฟสลัว รถเก่า ป้ายหน้ารถว่างเปล่า ไม่มีคนนั่ง — ว่างทั้งคันจึงมีที่ให้แป้งด้วย
        /// แป้งเป็นคนชี้คันนี้เองตอนมันมาจอด และโทนรถที่ดูไม่น่าไว้ใจคือตัวกับดักกลับด้าน:
        /// ผู้เล่นที่ไม่ได้อ่านเรื่องของแป้งจะไม่กล้าขึ้น
        /// </summary>
        Escape,

        /// <summary>
        /// คันที่ 3 — ความตาย
        ///
        /// ไฟในติดๆ ดับๆ มีรอยเลือดเต็มไปหมด ป้ายหน้ารถเป็นชื่อหมู่บ้านของผู้เล่น
        /// มีเงาคนนั่ง 5-6 คน = คนที่ไม่รอดจากกฎที่ผ่านมาทั้งหมด
        ///
        /// ขึ้นแล้วตายคนเดียว คนอื่นยังติดอยู่ใน loop เดิม
        /// </summary>
        Death,

        /// <summary>
        /// คันที่ 4 — วนลูป
        ///
        /// ไฟหน้าดับ เครื่องยนต์ไม่มีเสียง ตัวรถเปียกโชกเหมือนเพิ่งผ่านพายุทั้งที่คืนนี้ฝนไม่ตก
        /// ป้ายหน้ารถเขียนว่า "ศาลา" มีผู้โดยสารคนเดียวใส่เสื้อตัวเดียวกับผู้เล่น (คือผู้เล่นเอง)
        ///
        /// ขึ้นแล้วรถพาวนกลับมาจอดที่ศาลาหลังโค้ง เวลาย้อนเป็น 18:40 แล้วเริ่มคืนเดิมใหม่
        /// ทั้งคืน โดยแชทเก่ายังอยู่ครบ
        /// </summary>
        Loop,
    }
}
