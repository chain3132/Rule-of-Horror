using System.Collections.Generic;
using ScriptableObject;
using Sirenix.OdinInspector;
using UnityEngine;

[System.Serializable]
public class ChatNode
{
    [TextArea(2,5)]
    public string message;

    public bool isPlayer;

    // ─────────────────────────── บทพูดผู้เล่นที่ไม่ต้องให้เลือกตอบ ───────────────────────────
    // ปกติ isPlayer = หยุดรอให้ผู้เล่นเลือกคำตอบทุกครั้ง แต่บางจังหวะเราแค่อยากให้ตัวละคร
    // "พิมไปเอง" เป็นบทที่เขียนไว้ตายตัว (ทักกลับสั้นๆ / พิมค้างแล้วลบ / รับคำ) ไม่ใช่ทางแยก
    //
    // ค่าเริ่มต้นเป็น ✗ โดยตั้งใจ ไม่ใช่ ✓ — ChatNode ถูก serialize ไว้ใน ConversationData
    // ที่มีอยู่แล้วทั้งโปรเจกต์ ถ้า default เป็น ✓ node ที่มีตัวเลือกอยู่แล้วจะเลิกถามคำตอบ
    // พร้อมกันหมดแบบเงียบๆ แบบนี้ ✗ = พฤติกรรมเดิมเป๊ะ บทสนทนาเก่าไม่ต้องแตะเลย

    [ShowIf("isPlayer")]
    [Tooltip("✓ = เป็นบทพูดของผู้เล่นที่เขียนไว้ตายตัว แสดงแล้วไปต่อที่ Next Node เอง ไม่ต้องให้เลือกตอบ\n" +
             "✗ = หยุดรอให้ผู้เล่นเลือกตอบจาก Replies (พฤติกรรมเดิม)")]
    public bool scriptedLine;

    // ─────────────────────────── node ที่ให้เลือกรางวัล ───────────────────────────
    // หลังจบกฎแต่ละข้อ คนปริศนาจะให้เลือกรางวัล 1 อย่างจากสองอย่างที่สุ่มมา
    // ตัวเลือกสองอันนั้นสุ่มตอนเล่น ไม่ได้เขียนไว้ล่วงหน้า (รางวัลที่เคยได้แล้วจะไม่ออกมาอีก
    // อันที่ขึ้นมาแต่ไม่ได้เลือกยังมีสิทธิ์ออกรอบหลัง) จึงใส่ Replies เองไม่ได้ — RewardSystem เป็นคนสร้างให้ตอนนั้น
    //
    // ทั้งสองตัวเลือกไปต่อที่ Next Node เดียวกัน ข้อความของ node นั้นใส่ {reward} ไว้ได้
    // เดี๋ยวจะถูกแทนด้วยชื่อรางวัลที่ผู้เล่นเพิ่งเลือก (เช่น "ได้เลย เดี๋ยวจัด เทียน ไปให้")

    [ShowIf("isPlayer")]
    [Tooltip("✓ = node นี้คือจังหวะให้เลือกรางวัล ตัวเลือกจะถูกสุ่มมาให้ตอนเล่น (ไม่ต้องใส่ Replies เอง)\n" +
             "ทุกตัวเลือกจะไปต่อที่ Next Node เดียวกัน")]
    public bool offersReward;

    [ShowIf("@isPlayer && !scriptedLine && !offersReward")]
    [TableList]
    public List<ReplyOption> replies;

    [ShowIf("@!isPlayer || scriptedLine || offersReward")]
    public int nextNode;

    /// <summary>true = node นี้ต้องหยุดรอให้ผู้เล่นเลือกคำตอบ ไม่ใช่แค่แสดงแล้วไปต่อ</summary>
    public bool NeedsReply => isPlayer && !scriptedLine;

    // ─────────────────────────── บันทึกลงแอปกฎ ───────────────────────────
    // ในแชทจะมีจังหวะที่ขึ้นว่า "กฎข้อที่ N — บันทึกใน [3]" ตรงนั้นแหละคือ node ที่ติดช่องนี้
    //
    // ทำไมอยู่ที่ node ไม่ใช่ที่ ReplyOption: หลังผู้เล่นเลือกตอบ บทสนทนาจะแยกเป็นสองสาย
    // และตัวกฎถูกบันทึกใน node ของสายนั้นอยู่แล้ว ติดธงตรง node จึงได้ทั้ง "บันทึกเมื่อไร"
    // และ "บันทึกแบบไหน" มาฟรีๆ โดยไม่ต้องจำว่าผู้เล่นกดอะไรไปเมื่อกี้

    [Tooltip("ใส่กฎที่จะถูกบันทึกลงแอปกฎตอน node นี้ถูกแสดง — เว้นว่าง = ไม่บันทึกอะไร")]
    public RuleEntryData recordsRule;

    [ShowIf("@recordsRule != null")]
    [Tooltip("✓ = สายที่ผู้เล่นให้ความร่วมมือ (รู้เวลา รู้ครบ)\n" +
             "✗ = สายที่ผู้เล่นหัวแข็ง (เวลาเป็น --:-- รู้ไม่ครบ)")]
    public bool recordsAsCooperative = true;
}
